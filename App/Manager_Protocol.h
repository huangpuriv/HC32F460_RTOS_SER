#ifndef MANAGER_PROTOCOL_H
#define MANAGER_PROTOCOL_H

#include <stdint.h>

/*******************************************************************************
 * Manager_Protocol  --  "Energy Controller <-> F460 Manager" APDU 应答器
 *
 * 来源: DUAL_CDC_HC32F460_v2.1.7 1108 工程, usb_dev_dual_cdc (双 CDC) 的
 *       COM#1 / 接口1 通道, 原实现见
 *         midwares/.../device_class/cdc/usb_dev_cdc_class.c
 *         -> vApplicationOutDataProcess()   请求解析
 *         -> ucApplicationInDataProcess()  回发应答 (走 CDC_IF1_IN_EP)
 *
 * 已移植: 收发作载体换成 USART4 数据口 (PB14 = TX / PB15 = RX),
 *         帧界由硬件 RTO 判帧, 整帧完整送到本模块, 应答直接交 UART4_SendData() 发出。
 *
 *------------------------------------------------------------------------------
 * 标准依据 (本文件字段命名的正解):
 *   T/SMI 1017.4-2021 <<能源控制器软件及接口技术规范 第4部分: 功能模组接口协议>>
 *   本地文件: 8.能源控制器软件及接口技术规范 第4部分：功能模组接口协议.pdf
 *
 *   5.2   虚拟通道1 为管理通道(必须为 CDC-ACM), 本协议即该通道的接口控制协议
 *   6.2.1 帧格式: 68 | L(2B) | C(2B) | 数据域(L 字节) | FCS(2B) | 16
 *   6.2.2 长度域 L: 2 字节 BIN, bit0..bit11 = 数据域字节数, bit12..bit15 保留
 *   6.2.3 控制域 C: 2 字节。低位字节 = DIR(bit7) | PRM(bit6) | 控制码(bit5..bit0),
 *                   高位字节 = 帧序号 FID
 *          表1: DIR=0/PRM=1 为"终端发起的请求"; DIR=1/PRM=1 为"模组对终端请求的响应"
 *          表2: 控制码 00H 确认帧 / 01H 否认帧 / 02H 信息帧
 *          6.2.3.3: 帧序号 0~255 循环, 响应帧序号应与请求一致
 *   6.2.5 帧校验 FCS: 2 字节, 附录A 给出算法 = PPP FCS-16
 *          (P = 0x8408, 初值 0xFFFF, 逐字节查表, 末尾取反, 低字节在前,
 *           覆盖 L + C + 数据域, 不含起始字符 68 / 结束字符 16 / FCS 本身)
 *   7.4.1 APDU CHOICE: 请求 [1]链路协商 [2]数据读取 [3]设置 [4]上报通知
 *                     响应 [129]81H [130]82H [131]83H [132]84H
 *   7.4.7 Get-Result CHOICE: [0] 错误信息 DAR / [1] 数据 Data
 *   7.3.8 DAR 枚举: 0成功 1拒绝读写 2硬件失效 3信息类未定义 4暂时失效 5对象未定义 ...
 *   8.1   信息类标识 DT: DTA = (DTA1 << 4) | DTA2; DTA2: 0H只读 1H可读写 2H只写
 *   8.2   表23 DTA1=0H 通用信息类: 00H模组信息 01H链路协商信息 02H协议版本
 *         03H电源状态 04H文件传输状态 06H启动时间 / 1H:00H时钟 /
 *         2H: 00H硬件初始化 01H参数初始化 02H数据初始化 03H文件传输
 *------------------------------------------------------------------------------
 *
 * 本文件采用的帧结构 (字段下标以整帧首字节为 [0], n = 整帧字节数):
 *
 *   [0]      68               帧起始字符 (标准 6.2.1 标志)
 *   [1..2]   L                长度域, 2 字节 BIN, 低字节在前
 *                             标准 6.2.2 语义 = 数据域字节数; 恒有 n = L + 8
 *                             (8 = 68 1B + L 2B + C 2B + FCS 2B + 16 1B)
 *                             因 数据域 <= 4095, 高字节 bit12..bit15 恒为 0,
 *                             故实测与"n - 8"完全等价
 *   [3]      C 低位字节       DIR | PRM | 控制码
 *                             请求 0x42 = DIR=0(终端发出) PRM=1(终端发起) 控制码=02H
 *                             应答 0xC2 = DIR=1(模组发出) PRM=1(模组响应)   控制码=02H
 *   [4]      C 高位字节       帧序号 FID (标准 6.2.3.3: 响应应与请求一致)
 *   [5..]    数据域            APDU 标记 + 信息类标识 DT + 服务数据
 *   [n-3..n-2] FCS            帧校验 2 字节, 低字节在前 (标准 6.2.5 + 附录A)
 *   [n-1]    16               帧结束字符
 *
 * 数据域内部的字段 (本模块实际读的只有 [5] / [6] / [7]):
 *   [5]     APDU 标记         01H Link 02H Get 03H Set 04H Report
 *                             81H / 82H / 83H / 84H 为对应应答
 *   [6]     DT 高字节 = DTA   DTA1 = (DT >> 4) & 0x0F, DTA2 = DT & 0x0F
 *   [7]     DT 低字节 = DTB
 *
 * 信息类 DT 分派 (与源 USB CDC 工程逐字节一致的部分):
 *   APDU=01                        -> Link 链路协商       应答 83 字节
 *   APDU=02  DT 00.00.00           -> 模组信息            应答 122 字节
 *   APDU=02  DT 00.00.01           -> 链路协商信息        应答 103 字节
 *   APDU=02  DT 00.00.02           -> 协议版本            应答 15 字节
 *   APDU=02  DT 00.00.03           -> 电源状态            应答 14 字节
 *   APDU=03  DT 00.01.00           -> 设置时钟            应答 12 字节
 *   其他                           -> 只打印, 不回帧 (与源工程一致)
 *
 * 注: 6 条应答的 FCS 是原工程从实测抓包里抄下来的常量, 源工程既不校验收到的 FCS
 *     也不计算发出去的 FCS。已用附录A 算法逐条复核: 6 条的 L 与 FCS 全部自洽
 *     (L 均 = 帧长 - 8; FCS 均 = 计算值), 因此本文件一字节不改地保留, 可与真实模组直接对打。
 *
 *------------------------------------------------------------------------------
 * MANAGER_2021 开关 (默认 0 = 关闭)
 *
 *   0 = 与源 USB CDC 工程逐字节一致:
 *       只认 68 / L=[1] / C=[3] / APDU=[5] / DT=[6][7]; 不校验 FCS;
 *       L 与实际长度不符时仅打印告警仍照处理; 应答帧序号沿用常量表里硬编码的值。
 *
 *   1 = 按 T/SMI 1017.4-2021 补齐一致性行为, 逐项变更清单见 Manager_Protocol.c 顶部。
 *
 *   本开关只影响 Manager_Protocol 这一层的校验与应答构造, 完全不触碰
 *   USART4_DMA_RTO 的收发通路 (RX DMA + RTO 判帧 + TX DMA)。
 *------------------------------------------------------------------------------
 ******************************************************************************/
#ifndef MANAGER_2021
#define MANAGER_2021            0
#endif

/*------------------------------- 调试打印 -----------------------------------*
 * 0 = 全部关           省 Flash
 * 1 = 只要            (默认) 请求/应答各一条摘要
 * 2 = 摘要 + 全字节 HEX dump
 *---------------------------------------------------------------------------*/
#ifndef MGR_DEBUG_PRINT
#define MGR_DEBUG_PRINT         (1)
#endif

/*******************************************************************************
 * 处理一帧 "Energy Controller -> F460 Manager" 请求, 返回对应的应答帧。
 *
 * 入参: pFrame    = 收到的整帧 (UART4_FrameBuf), u16Len = 帧长 (u16Uart4RxLen)
 *       pu16RspLen= 出参, 应答帧长度
 * 返回: 应答帧首地址 (静态存储期: MANAGER_2021=0 时为 ROM 常量表, =1 时为内部 RAM 缓冲);
 *       NULL = 该帧不需要应答 (帧非法 / DT 不匹配 / 非 Manager 服务码)
 *
 * 只在任务上下文调用, 不涉硬件中断; 调用方随后用 UART4_SendData() 发出。
 * 调用方先取走应答帧指针再清帧标志, 否则阻塞发送期间到达的下一帧会被误当重帧丢弃。
 *
 * 仅在 UART4_MODE == USART4_DMA_RTO 下编译 (RTO 判帧才能保证取到整帧)。
 *
 * 注意: 返回的指针在下一次调用后即失效, 不要跨调用保留。
 ******************************************************************************/
const uint8_t *Manager_ProtocolResolve(const uint8_t *pFrame, uint16_t u16Len,
                                       uint16_t *pu16RspLen);

#endif /* MANAGER_PROTOCOL_H */
